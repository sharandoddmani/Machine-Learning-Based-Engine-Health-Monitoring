function bundle = trainFinalEngineModel(trainPath)
% The only input file is the publisher's training split.
requireEngineModelToolbox;
[X, y] = loadEngineSplit(trainPath, 15628);
[features, target] = engineSchema;
labels = [0 1];
settings = struct('MaxNumSplits', 30, 'SplitCriterion', 'gdi', ...
    'MinLeafSize', 1, 'Prior', 'empirical');
parameters = fitEnginePreprocessing(X);
standardized = applyEnginePreprocessing(X, parameters);
before = rng;
restoreRng = onCleanup(@() rng(before));
rng(42, 'twister');
tree = fitctree(standardized, y, 'PredictorNames', features, 'ClassNames', labels, ...
    'MaxNumSplits', settings.MaxNumSplits, 'SplitCriterion', settings.SplitCriterion, ...
    'MinLeafSize', settings.MinLeafSize, 'Prior', settings.Prior);
counts = [nnz(y == 0), nnz(y == 1)];
[~, majorityIndex] = max(counts);
bundle = struct('model', compact(tree), 'algorithm', 'Decision Tree', ...
    'hyperparameters', settings, 'preprocessing', parameters, 'featureNames', {features}, ...
    'classLabels', labels, 'targetName', target, 'trainingRows', size(X, 1), ...
    'trainingClassCounts', counts, 'majorityClass', labels(majorityIndex), ...
    'actualSplits', nnz(tree.IsBranchNode), 'seed', 42, 'matlabVersion', version, ...
    'toolboxVersion', ver('stats'), 'trainingTimestampUtc', ...
    char(datetime('now', 'TimeZone', 'UTC', 'Format', 'yyyy-MM-dd HH:mm:ss')));
end
