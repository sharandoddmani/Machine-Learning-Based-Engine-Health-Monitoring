function writeEnginePreprocessingReport(data, path, provenancePath)
[file, message] = fopen(path, 'w', 'n', 'UTF-8');
if file < 0, error('EngineData:Report', '%s', message); end
cleanup = onCleanup(@() fclose(file));
p = data.parameters;
fprintf(file, 'Stage 2 preprocessing report (MATLAB %s)\n\n', version('-release'));
fprintf(file, 'Input order: %s\n', strjoin(p.featureNames, ', '));
fprintf(file, 'Target: engine_condition (Class 0 and Class 1)\n');
fprintf(file, 'Each source record has six numeric sensors and one numeric target.\n');
fprintf(file, '\n%-22s %7s %18s %18s\n', 'Split', 'Rows', 'Class 0', 'Class 1');
labels = {data.yTrain, data.yDevelopment, data.yValidation, data.yTest};
names = {'Publisher training', 'Development-training', 'Validation', 'Publisher test'};
for k = 1:numel(names)
    y = labels{k};
    fprintf(file, '%-22s %7d %8d (%6.2f%%) %8d (%6.2f%%)\n', names{k}, ...
        numel(y), nnz(y == 0), 100*mean(y == 0), nnz(y == 1), 100*mean(y == 1));
end
fprintf(file, ['\nBoth CSVs passed schema and finite-value checks. Zero missing or nonfinite values.\n' ...
    'Missing or nonfinite values cause an error. No rows are imputed or removed.\n' ...
    'Potential outlier counts and sensor comparisons are in feature_analysis.txt.\n' ...
    'Stratification uses MT19937 seed %d and rounds the 20%% holdout count per class.\n' ...
    'Validation workflow: fit on development-training sensors only.\n' ...
    'Subtract the fitted mean and divide by the sample standard deviation (N-1).\n' ...
    'Use a divisor of 1 for zero standard deviations. Use the same fit for validation.\n' ...
    'Final workflow after model choices: refit on all publisher training rows, then\n' ...
    'apply that fit to the original test sensors for final evaluation.\n' ...
    'Stage 2 checks the test transform for finiteness and shape. Test features and labels\n' ...
    'are excluded from the fit, split selection, feature analysis and saved MAT file.\n' ...
    'Exploration covers the full publisher training split and retains all six sensors.\n' ...
    'Stage 3 benchmark is pending project-guide approval.\n'], data.seed);
fprintf(file, '\n%-22s %17s %17s %17s\n', 'Feature', 'Fitted mean', 'Fitted sample SD', 'Divisor');
for k = 1:numel(p.featureNames)
    fprintf(file, '%-22s %17.10g %17.10g %17.10g\n', p.featureNames{k}, p.mean(k), p.std(k), p.scale(k));
end
fprintf(file, '\n%s', fileread(provenancePath));
end
