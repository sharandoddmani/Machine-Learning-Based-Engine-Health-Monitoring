function prepared = prepareEngineData(rawDir)
% Fit before loading the publisher test split. Labels are returned separately.
[train, yTrain] = loadEngineSplit(fullfile(rawDir, 'train.csv'), 15628);
[development, validation] = splitEngineTraining(yTrain);
parameters = fitEnginePreprocessing(train(development, :));
[test, yTest] = loadEngineSplit(fullfile(rawDir, 'test.csv'), 3907);
prepared = struct('train', train, 'yTrain', yTrain, ...
    'developmentIndices', development, 'validationIndices', validation, ...
    'XDevelopment', applyEnginePreprocessing(train(development, :), parameters), ...
    'XValidation', applyEnginePreprocessing(train(validation, :), parameters), ...
    'XTest', applyEnginePreprocessing(test, parameters), ...
    'yDevelopment', yTrain(development), 'yValidation', yTrain(validation), ...
    'yTest', yTest, 'parameters', parameters, 'seed', 42);
end
